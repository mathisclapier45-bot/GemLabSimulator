def build():
    species_to_group = {}
    for group, ids in SPECIES.items():
        assert group in G, group
        for i in ids:
            assert i not in species_to_group, i
            species_to_group[i] = group
    out = {}
    for sid, group in species_to_group.items():
        tough, stab, fr, en = G[group]
        o = OVERRIDE.get(sid)
        if o:
            tough, stab = o[0], o[1]
            if o[2]:
                fr, en = o[2], o[3]
        out[sid] = {"toughness": tough, "stability": stab, "fr": fr, "en": en}
    return out


def main():
    care = build()
    from app import catalog
    ids = [s["id"] for s in catalog.data()["species"]]
    missing = [i for i in ids if i not in care]
    extra = [i for i in care if i not in ids]
    if missing:
        print("SANS ENTRÉE :", missing)
    if extra:
        print("INCONNUES   :", extra)
    path = ROOT / "data" / "care.json"
    path.write_text(json.dumps(care, ensure_ascii=False, indent=1, sort_keys=True) + "\n", encoding="utf-8")
    print("{} espèces écrites dans {}".format(len(care), path))
    return 1 if missing or extra else 0


if __name__ == "__main__":
    sys.exit(main())
